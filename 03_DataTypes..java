class datatypes{
    public static void main(String a[]){

        int integer_num = 23;
        short short_int = 23;
        byte very_short_int = 12;  //-128 to 127
        long long_int = 834l;  //Don't forget to add l at the end of the number.

        float floating_pt_number =89.65f;  //Don't forget to add f at the end of the number.
        double larger_float = 544.54;  //Deafaut in java

        char character = 'c';

        boolean true_false_t = true;
        boolean true_false_f = false;

        // PRINT

        System.out.println("int: " + integer_num);
        System.out.println("short: " + short_int);
        System.out.println("byte: " + very_short_int);
        System.out.println("long: " + long_int);
        System.out.println("float: " + floating_pt_number);
        System.out.println("double: " + larger_float);
        System.out.println("char: " + character);
        System.out.println("boolean_true: " + true_false_t);
        System.out.println("boolean_false: " + true_false_f);

    }
}