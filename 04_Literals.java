class literals{
    public static void main(String s[]){
        // Literals

        // Binary
        System.out.println(0b101); //The binary num that comes after 0b is evaluated and printed.

        // Hexadecial
        System.out.println(0x7e); //The hexadecimal code that comes after 0x is evaluated and printed.

        //No of zeroes
        int num1 = 101_00_570;
        System.out.println(num1);

        //"e" for power
        double num2 = 12450e21;
        System.out.println(num2); //"e" can be used to represent power

        //char adding 
        char character = 'a';
        character +=1; //or character++
        System.out.println(character); //"e" can be used to represent power
    }
}